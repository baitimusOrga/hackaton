-- Keep the SQL portable (Postgres in dev/staging/prod, H2 in PostgreSQL mode for tests).

create table app_user (
    id            bigint generated by default as identity primary key,
    email         varchar(254) not null unique,
    password_hash varchar(100) not null,
    display_name  varchar(80)  not null,
    created_at    timestamp with time zone not null
);

create table listing (
    id          bigint generated by default as identity primary key,
    owner_id    bigint        not null references app_user (id),
    title       varchar(120)  not null,
    description varchar(4000) not null,
    price_cents integer,
    image_key   varchar(80),
    created_at  timestamp with time zone not null
);

create index listing_created_at_idx on listing (created_at desc);
create index listing_owner_idx on listing (owner_id);
