create table listing (
    id bigint generated by default as identity (start with 4) primary key,
    title varchar(120) not null,
    description varchar(4000) not null,
    price_chf numeric(12,2) not null,
    condition varchar(20) not null,
    category varchar(80) not null,
    postcode varchar(4) not null,
    locality varchar(120) not null,
    image_url varchar(500),
    created_at timestamp with time zone not null
);
create table listing_attribute (
    listing_id bigint not null references listing(id),
    name varchar(80) not null,
    attribute_value varchar(500) not null,
    primary key (listing_id, name)
);
create index listing_created_at_idx on listing(created_at desc);

