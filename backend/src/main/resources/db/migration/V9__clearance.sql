create table clearance_project (
    id bigint generated by default as identity primary key,
    owner_id varchar(255) not null,
    company_name varchar(120) not null,
    postcode varchar(4) not null,
    locality varchar(120) not null,
    deadline date not null,
    route varchar(20),
    created_at timestamp with time zone not null
);
create index clearance_project_owner_idx on clearance_project(owner_id);

create table clearance_item (
    id bigint generated by default as identity primary key,
    project_id bigint not null references clearance_project(id),
    name varchar(120) not null,
    category varchar(80) not null,
    quantity integer not null,
    quantity_confirmed boolean default false not null,
    condition varchar(20) not null,
    notes varchar(1000),
    estimated_unit_chf numeric(12,2) not null,
    listing_id bigint references listing(id)
);
create index clearance_item_project_idx on clearance_item(project_id);
