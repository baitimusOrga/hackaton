alter table listing add column sale_mode varchar(20) default 'FIXED' not null;
alter table listing add column ends_at timestamp with time zone;
alter table listing add column current_bid_chf numeric(12,2);
alter table listing add column bid_count integer default 0 not null;

create table bid (
    id bigint generated by default as identity primary key,
    listing_id bigint not null references listing(id),
    bidder_id varchar(255) not null,
    bidder_name varchar(120) not null,
    max_chf numeric(12,2) not null,
    created_at timestamp with time zone not null
);
create index bid_listing_idx on bid(listing_id, max_chf desc, created_at);

