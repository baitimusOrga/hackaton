-- Reintroduce real accounts; V1-V3 remain immutable.
create table app_user (
    id bigint generated by default as identity primary key,
    email varchar(254) not null unique,
    password_hash varchar(255) not null,
    display_name varchar(80) not null,
    location varchar(120) not null default '',
    canton varchar(2),
    contact_preference varchar(10) not null default 'IN_APP',
    created_at timestamp with time zone not null,
    reset_token_hash varchar(64) unique,
    reset_expires_at timestamp with time zone,
    constraint contact_preference_check check (contact_preference in ('IN_APP', 'EMAIL')),
    constraint canton_check check (canton is null or canton in
        ('AG','AI','AR','BE','BL','BS','FR','GE','GL','GR','JU','LU','NE',
         'NW','OW','SG','SH','SO','SZ','TG','TI','UR','VD','VS','ZG','ZH'))
);

-- Spring Session JDBC's schema; BYTEA also works in H2 PostgreSQL mode.
create table spring_session (
    primary_id char(36) not null primary key,
    session_id char(36) not null,
    creation_time bigint not null,
    last_access_time bigint not null,
    max_inactive_interval integer not null,
    expiry_time bigint not null,
    principal_name varchar(254)
);
create unique index spring_session_ix1 on spring_session (session_id);
create index spring_session_ix2 on spring_session (expiry_time);
create index spring_session_ix3 on spring_session (principal_name);
create table spring_session_attributes (
    session_primary_id char(36) not null references spring_session(primary_id) on delete cascade,
    attribute_name varchar(200) not null,
    attribute_bytes bytea not null,
    primary key (session_primary_id, attribute_name)
);
