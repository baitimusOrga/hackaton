-- Public questions on a listing; the seller answers (the answer can be edited).
create table listing_question (
    id bigint generated by default as identity primary key,
    listing_id bigint not null references listing(id),
    asker_id varchar(255) not null,
    asker_name varchar(120) not null,
    question_text varchar(1000) not null,
    created_at timestamp with time zone not null,
    answer varchar(1000),
    answered_at timestamp with time zone
);
create index listing_question_listing_idx on listing_question(listing_id, created_at);
